"""Generate ViewingTonight/Data/MessierCatalog.swift from the Android app's MessierCatalog.kt,
so the two apps share exactly the same 110-object table. Usage:
    python3 gen_messier.py <path to MessierCatalog.kt> <output .swift>"""
import re, sys

src = open(sys.argv[1], encoding="utf-8").read()

def block(name):
    m = re.search(name + r"[^=]*=\s*mapOf\((.*?)\n    \)", src, re.S)
    return m.group(1)

names = dict((int(n), s) for n, s in re.findall(r'(\d+) to "([^"]*)"', block("commonNames")))
mags = dict((int(n), v) for n, v in re.findall(r'(\d+) to ([\d.]+)', block("magnitudes")))
raw = re.findall(r'Raw\((\d+), "([^"]*)", ([-\d.]+), ([-\d.]+)\)', src)
assert len(raw) == 110 and len(mags) == 110, (len(raw), len(mags))

def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = [
    "import Foundation",
    "",
    "// GENERATED by Tools/gen_messier.py from the Android app's data/MessierCatalog.kt — do not edit by hand.",
    "// J2000 RA/Dec (decimal degrees), object type, common name where well established, and",
    "// apparent magnitude (skyatnightmagazine.com's Messier reference table).",
    "",
    "nonisolated enum MessierCatalog {",
    "    static let entries: [MessierEntry] = [",
]
for n, t, ra, dec in raw:
    n = int(n)
    cn = q(names[n]) if n in names else "nil"
    out.append(f"        MessierEntry(number: {n}, objectType: {q(t)}, raDeg: {ra}, decDeg: {dec}, commonName: {cn}, apparentMagnitude: {mags[n]}),")
out += ["    ]", "}", ""]
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out))
print("wrote", len(raw), "entries")
