"""Emit ViewingTonightTests/AstroGoldenTests.swift from the Kotlin mirror."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kotlin_mirror import *
from datetime import datetime, timezone

def ep(*a): return int(datetime(*a, tzinfo=timezone.utc).timestamp())
def f(x): return repr(float(x))

WAA = (41.0340, -73.7629)          # White Plains, NY (Westchester)
SOUTH = (-33.8688, 151.2093)       # Sydney — southern hemisphere / east longitude
ARCTIC = (69.6492, 18.9553)        # Tromsø — circumpolar / midnight-sun cases

instants = [ep(2026, 11, 2, 3, 0), ep(2027, 1, 15, 4, 30), ep(2026, 6, 21, 12, 0), ep(2030, 3, 10, 0, 0)]

L = []
w = L.append
w("// GENERATED by make_goldens.py from a line-for-line mirror of the Android app's astro/*.kt.")
w("// Expected values = what the Kotlin code computes. If a test fails, the Swift port diverged.")
w("import Foundation")
w("import Testing")
w("@testable import ViewingTonight")
w("")
w("private func jd(_ epoch: TimeInterval) -> Double { JulianDate.from(Date(timeIntervalSince1970: epoch)) }")
w("private let tol = 1e-9   // degrees; leaves room for last-bit libm differences between JVM and Apple platforms")
w("// Azimuth comes from acos(), which amplifies last-bit differences near due N/S (e.g. at an object's")
w("// highest point), so it gets a looser bound: 1e-6 deg = 0.0036 arcsec, still far below display precision.")
w("private let azTol = 1e-6")
w("")
w("@Suite(\"Astro matches Kotlin\") struct AstroGoldenTests {")
w("")

# --- point functions at several instants
w("    @Test func siderealSunMoon() {")
for t in instants:
    j = jd_from_epoch(t)
    w(f"        // {datetime.fromtimestamp(t, timezone.utc).isoformat()}")
    w(f"        #expect(abs(jd({t}) - {f(j)}) < 1e-9)")
    w(f"        #expect(abs(SiderealTime.greenwichMeanSiderealTimeDegrees(jd({t})) - {f(gmst(j))}) < tol)")
    sr, sd = sun(j)
    w(f"        do {{ let s = SunPosition.geocentricEquatorial(jd({t})); #expect(abs(s.rightAscensionDeg - {f(sr)}) < tol); #expect(abs(s.declinationDeg - {f(sd)}) < tol) }}")
    mr, md, mp = moon(j)
    w(f"        do {{ let m = MoonPosition.geocentric(jd({t})); #expect(abs(m.equatorial.rightAscensionDeg - {f(mr)}) < tol); #expect(abs(m.equatorial.declinationDeg - {f(md)}) < tol); #expect(abs(m.horizontalParallaxDeg - {f(mp)}) < tol) }}")
    w(f"        #expect(abs(MoonPosition.illuminatedFraction(jd({t})) - {f(moon_illum(j))}) < tol)")
    w(f"        #expect(abs(MoonPosition.apparentMagnitude(jd({t})) - {f(moon_mag(j))}) < 1e-7)")
w("    }")
w("")
w("    @Test(arguments: Planet.allCases) func planets(_ planet: Planet) {")
w("        switch planet {")
for name in PLANETS:
    w(f"        case .{name}:")
    for t in instants:
        r, d = planet(name, jd_from_epoch(t))
        w(f"            do {{ let p = PlanetPositions.geocentricEquatorial(.{name}, jd: jd({t})); #expect(abs(p.rightAscensionDeg - {f(r)}) < tol); #expect(abs(p.declinationDeg - {f(d)}) < tol) }}")
w("        }")
w("    }")
w("")

# --- alt/az for a fixed object from three observers
M31 = (10.6847, 41.2690)
w("    @Test func horizontalAndCompass() {")
w("        let m31 = EquatorialCoordinates(rightAscensionDeg: 10.6847, declinationDeg: 41.2690)")
for (lat, lon) in (WAA, SOUTH, ARCTIC):
    for t in instants:
        alt, az = to_horizontal(*M31, lat, lon, jd_from_epoch(t))
        w(f"        do {{ let h = m31.toHorizontal(observer: Observer(latitudeDeg: {lat}, longitudeDeg: {lon}), jd: jd({t})); #expect(abs(h.altitudeDeg - {f(alt)}) < tol); #expect(abs(h.azimuthDeg - {f(az)}) < azTol); #expect(h.azimuthDeg.cardinalDirection == \"{cardinal(az)}\") }}")
for az in (0.0, 22.4, 22.5, 67.6, 180.0, 337.4, 337.5, 359.9, 360.0, -45.0, 720.1):
    w(f"        #expect(({az}).cardinalDirection == \"{cardinal(az)}\")")
w("    }")
w("")

# --- AltitudeSampler over real viewing sessions (6pm-6am local, given here in UTC)
def opt(ms): return "nil" if ms is None else f"Date(timeIntervalSince1970: {ms / 1000!r})"
cases = [
    ("WAA Nov 1-2 2026 session", WAA, ep(2026, 11, 1, 23, 0), ep(2026, 11, 2, 11, 0)),
    ("WAA Jun 21-22 2026 session", WAA, ep(2026, 6, 21, 22, 0), ep(2026, 6, 22, 10, 0)),
    ("Sydney Nov 2 2026 session", SOUTH, ep(2026, 11, 2, 7, 0), ep(2026, 11, 2, 19, 0)),
    ("Tromso Jun 21 2026 session", ARCTIC, ep(2026, 6, 21, 16, 0), ep(2026, 6, 22, 4, 0)),
]
targets = [
    ("sun", "{ SunPosition.geocentricEquatorial($0) }", lambda j: sun(j), -0.8333),
    ("moon", "{ MoonPosition.geocentric($0).equatorial }", lambda j: moon(j)[:2], None),
    ("M42", "{ _ in EquatorialCoordinates(rightAscensionDeg: 83.8221, declinationDeg: -5.3911) }", lambda j: (83.8221, -5.3911), -0.5667),
    ("M31", "{ _ in EquatorialCoordinates(rightAscensionDeg: 10.6847, declinationDeg: 41.2690) }", lambda j: M31, -0.5667),
    ("jupiter", "{ PlanetPositions.geocentricEquatorial(.jupiter, jd: $0) }", lambda j: planet("jupiter", j), -0.5667),
]
w("    private func check(_ w: VisibilityWindow, ever: Bool, always: Bool, rise: Date?, set: Date?, maxT: Date, maxAlt: Double, maxAz: Double) {")
w("        #expect(w.risesAboveThreshold == ever)")
w("        #expect(w.alwaysAboveThreshold == always)")
w("        #expect((w.riseTime == nil) == (rise == nil)); if let a = w.riseTime, let b = rise { #expect(abs(a.timeIntervalSince(b)) <= 0.002) }")
w("        #expect((w.setTime == nil) == (set == nil)); if let a = w.setTime, let b = set { #expect(abs(a.timeIntervalSince(b)) <= 0.002) }")
w("        #expect(w.maxAltitudeTime == maxT)")
w("        #expect(abs(w.maxAltitudeDeg - maxAlt) < tol)")
w("        #expect(abs(w.azimuthAtMax - maxAz) < azTol)")
w("    }")
w("")
w("    @Test func altitudeSampler() {")
for label, (lat, lon), start, end in cases:
    w(f"        // {label}")
    w(f"        do {{")
    w(f"            let obs = Observer(latitudeDeg: {lat}, longitudeDeg: {lon})")
    w(f"            let start = Date(timeIntervalSince1970: {start}), end = Date(timeIntervalSince1970: {end})")
    for name, swift_pos, pos, thr in targets:
        if name == "moon":
            par = moon(jd_from_epoch(start))[2]
            thr = 0.7275 * par - 0.5667
            swift_thr = f"RiseSetThresholds.moon(horizontalParallaxDeg: MoonPosition.geocentric(JulianDate.from(start)).horizontalParallaxDeg)"
        else:
            swift_thr = "RiseSetThresholds.sun" if name == "sun" else "RiseSetThresholds.starOrPlanet"
        r = sample(pos, lat, lon, start, end, thr)
        w(f"            check(AltitudeSampler.sample(observer: obs, position: {swift_pos}, start: start, end: end, thresholdDeg: {swift_thr}),")
        w(f"                  ever: {str(r['ever']).lower()}, always: {str(r['always']).lower()}, rise: {opt(r['rise_ms'])}, set: {opt(r['set_ms'])},")
        w(f"                  maxT: Date(timeIntervalSince1970: {r['max_t']}), maxAlt: {f(r['max_alt'])}, maxAz: {f(r['max_az'])})  // {name}")
    w("        }")
# chart series length + odd-length window (end not on a step boundary)
s = series(lambda j: M31, *WAA, ep(2026, 11, 1, 23, 0), ep(2026, 11, 2, 11, 7), 30)
w(f"        do {{")
w(f"            let s = AltitudeSampler.series(observer: Observer(latitudeDeg: {WAA[0]}, longitudeDeg: {WAA[1]}), position: {{ _ in EquatorialCoordinates(rightAscensionDeg: 10.6847, declinationDeg: 41.2690) }}, start: Date(timeIntervalSince1970: {ep(2026,11,1,23,0)}), end: Date(timeIntervalSince1970: {ep(2026,11,2,11,7)}), stepMinutes: 30)")
w(f"            #expect(s.count == {len(s)})")
w(f"            #expect(s.last?.time == Date(timeIntervalSince1970: {s[-1][0]}))")
w(f"            #expect(abs((s.last?.altitudeDeg ?? .nan) - {f(s[-1][1])}) < tol)")
w(f"        }}")
w("    }")
w("}")

out = sys.argv[1]
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(L) + "\n")
print("wrote", out, len(L), "lines")
